    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        hapusTandaKesalahan();

        // Aturan 1: nama wajib diisi (spasi saja dianggap kosong)
        String nama = txtNama.getText().trim();
        if (nama.isEmpty()) {
            tampilkanKesalahan("Nama barang wajib diisi", txtNama);
            return;
        }

        // Aturan 2: nama tidak boleh ganda (huruf besar/kecil dianggap sama)
        if (model.sudahAda(nama)) {
            tampilkanKesalahan("Barang " + nama + " sudah ada di daftar", txtNama);
            return;
        }

        // Aturan 3: harga angka bulat 1 sampai 10000000 tanpa titik
        Integer harga = bacaHarga(txtHarga.getText());
        if (harga == null) {
            tampilkanKesalahan("Harga harus angka 1 sampai " + HARGA_MAKSIMAL, txtHarga);
            return;
        }

        try {
            spnJumlah.commitEdit(); // pastikan angka yang diketik di spinner terbaca
        } catch (ParseException e) {
            // abaikan, pakai nilai terakhir yang valid
        }
        Kategori kategori = Kategori.values()[cmbKategori.getSelectedIndex()];
        int jumlah = (Integer) spnJumlah.getValue();

        model.tambah(new Barang(nama, kategori, harga, jumlah));
        kosongkanForm();
        perbaruiRingkasan();
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnBersihkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBersihkanActionPerformed
        kosongkanForm();
    }//GEN-LAST:event_btnBersihkanActionPerformed

    /**
     * Membaca harga dari teks. Mengembalikan null jika tidak valid
     * (bukan angka bulat, ada titik/huruf, atau di luar rentang 1..10000000).
     */
    private Integer bacaHarga(String teks) {
        String bersih = teks.trim();
        if (!bersih.matches("\\d{1,8}")) {
            return null;
        }
        int nilai = Integer.parseInt(bersih);
        return (nilai >= 1 && nilai <= HARGA_MAKSIMAL) ? nilai : null;
    }

    /** Tampilkan pesan merah, pindahkan kursor ke isian salah, isian lain tidak dihapus. */
    private void tampilkanKesalahan(String pesan, JComponent isianSalah) {
        lblPesan.setText(pesan);
        isianSalah.putClientProperty("JComponent.outline", "error"); // garis merah FlatLaf
        isianSalah.requestFocusInWindow();
    }

    private void hapusTandaKesalahan() {
        lblPesan.setText("");
        txtNama.putClientProperty("JComponent.outline", null);
        txtHarga.putClientProperty("JComponent.outline", null);
    }

    /** Mengembalikan form ke keadaan awal. */
    private void kosongkanForm() {
        hapusTandaKesalahan();
        txtNama.setText("");
        txtHarga.setText("");
        cmbKategori.setSelectedIndex(0);
        spnJumlah.setValue(1);
        txtNama.requestFocusInWindow();
    }

    private void perbaruiRingkasan() {
        lblRingkasan.setText("Total " + BarangTableModel.formatRupiah(model.getTotal())
                + ", diskon " + BarangTableModel.formatRupiah(model.getDiskon())
                + ", bayar " + BarangTableModel.formatRupiah(model.getBayar()));
    }

